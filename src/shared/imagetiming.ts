/**
 * 圖片這條路上的**所有上限時間,放在同一個檔案裡**。
 *
 * 它們不是各自獨立的數字,是一組**有順序的**數字:
 *
 * ```
 * 抓圖 20s  <  模型 100s  <  (孤兒 120s + alarm 30s = 150s)  <  看門狗 180s
 * ```
 *
 * 由內而外遞增,每一層都要留給下一層說話的機會。順序錯了不會有任何
 * 症狀 —— 直到使用者先看到「沒有回應」,worker 的真正原因才姍姍來遲,
 * 然後兩邊各說一套(`docs/deviations.md` §DI)。
 *
 * 分散在三個檔案裡時,這個順序沒有任何地方寫得出來,也沒有任何測試
 * 抓得到。所以它們搬到這裡 —— 常數的**位置**本身就是那條不變量的宣告。
 */

/**
 * 抓圖 bytes 的上限。
 *
 * 比模型那一段短很多是刻意的:抓 bytes 是本地頻寬的事,20 秒還沒拿到
 * 就不是「慢」而是「不會來了」,而後面還排著一段幾十秒的模型呼叫。
 */
export const FETCH_TIMEOUT_MS = 20_000;

/**
 * 視覺呼叫的上限。
 *
 * 100 秒是「量到的最慢再加一截」:gemma 實測 9–68 秒
 * (`docs/plan-images.md` §13)。**必須小於看門狗**,否則使用者先看到
 * 「沒有回應」,worker 的錯誤才到。
 */
export const VISION_TIMEOUT_MS = 100_000;

/**
 * hover 進來但一直沒輪到的,離開視線就取消。
 *
 * 沒有這一條的話,滑鼠掃過長文章的二十張圖會排出一條二十分鐘的隊,
 * 而使用者早就捲過去了 —— 花的是配額,換到的是沒人看的加註。
 */
export const STALE_L0_MS = 10_000;

/**
 * 任何一條道的**上限年齡**:超過就收掉,不分 lane。
 *
 * 這條和 `STALE_L0_MS` 治的是兩件事。那條治的是「使用者早就捲過去了」,
 * 所以只管自動來的 l0。這一條治的是 **service worker 被回收留下的孤兒**:
 * `runImage` 停在半路,in-flight 集合隨 worker 一起消失,佇列卻在
 * `storage.session` 裡活著。l1 以前沒有過期線,於是那筆孤兒每次 worker
 * 醒來都被重新派工一次 —— 花掉配額,而 content 早就放棄了。
 *
 * 還在跑的工作不會被誤判:它在 in-flight 集合裡,本來就不看年齡。
 */
export const ORPHAN_MS = 120_000;

/**
 * content 這一側的最後一道防線。
 *
 * 送出去之後沒有任何回音(worker 死在半路、訊息掉了),這裡負責把狀態
 * 交還給使用者 —— 「卡住」不可以是一個能永久停留的狀態
 * (`docs/lessons.md` §10-quater)。
 *
 * 它是**最外層**,所以要比 worker 能自己說出口的每一種情況都晚:
 * 也不要在還會回來的請求上先說失敗。
 */
export const IMAGE_WATCHDOG_MS = 180_000;
